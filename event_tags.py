"""Категории мероприятий и совместимость со старыми названиями тегов."""
import json

GROUPS = {
    'art': ('🎭 Вид искусства', ['Балет', 'Выставки', 'Драмы', 'Комедии', 'Спектакли', 'Хореография', 'Мюзиклы']),
    'age': ('🎂 Возрастная категория', ['До 3 лет', 'От 3-6 лет', 'От 7-11 лет', 'От 12-15 лет', 'От 16-18 лет']),
    'music': ('🎵 Музыкальные', ['Джаз', 'Живая музыка', 'Классика', 'Концерты', 'Поп-музыка', 'Рок', 'Шансон', 'Хип-хоп', 'Народная музыка']),
    'activity': ('✨ Активности', ['Лекции', 'Мастер-классы', 'Пешие экскурсии', 'Саморазвитие', 'Цирковое шоу', 'Шоу', 'Экскурсии', 'Волонтерство', 'Движение Первых']),
}
AGES = GROUPS['age'][1]
ALL_TAGS = set(tag for _, tags in GROUPS.values() for tag in tags)
ALIASES = {
    'Пешеходные экскурсии': 'Пешие экскурсии',
    'волонтёрство': 'Волонтерство', 'Волонтёрство': 'Волонтерство', 'волонтерство': 'Волонтерство',
    'Детям до 3 лет': 'До 3 лет',
    'Детям от 3 до 6 лет': 'От 3-6 лет',
    'Детям от 7 до 11 лет': 'От 7-11 лет',
    'Детям от 12 до 15 лет': 'От 12-15 лет',
    'Детям от 16 до 18 лет': 'От 16-18 лет',
    '3–6 лет': 'От 3-6 лет', '7–11 лет': 'От 7-11 лет',
    '12–15 лет': 'От 12-15 лет', '16–18 лет': 'От 16-18 лет',
    'Классическая музыка': 'Классика',
    'Детский спектакль': 'Спектакли',
    'Шоу для детей': 'Шоу',
    'Юмор': 'Комедии',
}

def canonical(tag):
    name = str(tag).strip()
    return ALIASES.get(name, name)

def normalize(tags):
    if isinstance(tags, str):
        try:
            tags = json.loads(tags)
        except (ValueError, TypeError):
            tags = [part.strip() for part in tags.split(',')]
    if not isinstance(tags, list):
        return []
    result = []
    for raw in tags:
        tag = canonical(raw)
        if tag in ALL_TAGS and tag not in result:
            result.append(tag)
    return result
